// Package cli defines the cobra command tree for the vidify CLI.
// It is the driving adapter: it parses flags, binds them to Viper,
// and delegates all work to the application service via the app.Processor port.
package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"

	"github.com/spf13/cobra"
	"github.com/spf13/viper"
)

// cfgFile holds the optional explicit config file path from --config flag.
var cfgFile string

// rootCmd is the top-level `vidify` command.
var rootCmd = &cobra.Command{
	Use:   "vidify",
	Short: "Convert audio files into MP4 videos with burned-in subtitles",
	Long: `Vidify converts audio files (MP3, WAV, M4A, OGG, FLAC) into MP4 videos
with accurate, burned-in subtitles generated by Whisper.cpp.

Everything runs locally — no data is uploaded anywhere.

Example:
  vidify -i podcast.mp3
  vidify -i podcast.mp3 -m medium -o ./output
  vidify -i ./audio_folder/ -m small -l en`,

	// SilenceUsage prevents cobra from printing usage on every error.
	// We only want usage for --help, not for runtime errors.
	SilenceUsage: true,

	RunE: runRoot,
}

// Execute is called by main.go. It sets up viper config binding
// and runs the root command.
func Execute() error {
	return rootCmd.Execute()
}

func init() {
	// cobra.OnInitialize runs before any command's RunE.
	// We use it to load config file and environment variables.
	cobra.OnInitialize(initConfig)

	// --- Persistent flags (available to all subcommands) ---
	rootCmd.PersistentFlags().StringVar(&cfgFile, "config", "", "config file (default: $HOME/.vidify.yaml)")
	rootCmd.PersistentFlags().BoolP("verbose", "v", false, "enable debug logging")

	// --- Local flags (only for the root command) ---
	rootCmd.Flags().StringP("input", "i", "", "input audio file or directory (required)")
	rootCmd.Flags().StringP("model", "m", "medium", "whisper model: tiny|base|small|medium|large")
	rootCmd.Flags().StringP("language", "l", "auto", "language code (e.g. en, zh, ja) or 'auto'")
	rootCmd.Flags().Bool("translate", false, "translate non-English speech to English")
	rootCmd.Flags().String("bg-image", "", "background image path (default: built-in)")
	rootCmd.Flags().StringP("output", "o", "", "output directory (default: current directory)")

	// Mark input as required so cobra rejects missing input before we run.
	rootCmd.MarkFlagRequired("input")

	// Bind all flags to viper so config file / env vars can override them.
	// Viper key names match the flag names.
	viper.BindPFlag("verbose", rootCmd.PersistentFlags().Lookup("verbose"))
	viper.BindPFlag("input", rootCmd.Flags().Lookup("input"))
	viper.BindPFlag("model", rootCmd.Flags().Lookup("model"))
	viper.BindPFlag("language", rootCmd.Flags().Lookup("language"))
	viper.BindPFlag("translate", rootCmd.Flags().Lookup("translate"))
	viper.BindPFlag("bg-image", rootCmd.Flags().Lookup("bg-image"))
	viper.BindPFlag("output", rootCmd.Flags().Lookup("output"))
}

// initConfig reads the config file and environment variables.
// Priority: flags > env > config file > defaults.
func initConfig() {
	if cfgFile != "" {
		viper.SetConfigFile(cfgFile)
	} else {
		home, err := os.UserHomeDir()
		if err == nil {
			viper.AddConfigPath(home)
		}
		viper.AddConfigPath(".")
		viper.SetConfigName(".vidify")
		viper.SetConfigType("yaml")
	}

	// Environment variables: VIDIFY_MODEL, VIDIFY_LANGUAGE, etc.
	viper.SetEnvPrefix("VIDIFY")
	viper.AutomaticEnv()

	// Silently ignore missing config file — it's optional.
	viper.ReadInConfig()
}

// resolveWhisperBin finds the whisper-cli binary. It checks:
// 1. Explicit viper config (whisper-bin key)
// 2. third_party/whisper/<platform>/ relative to the executable
// 3. Falls back to the bare binary name (expects it on PATH)
//
// This logic lives in the CLI adapter because bundled-binary discovery
// is a deployment concern, not a domain or config-mapping concern.
func resolveWhisperBin() string {
	if bin := viper.GetString("whisper-bin"); bin != "" {
		return bin
	}

	// Try to find whisper-cli next to the executable.
	// This supports the bundled distribution where whisper binaries
	// ship inside third_party/whisper/<os>-<arch>/.
	exePath, err := os.Executable()
	if err == nil {
		exeDir := filepath.Dir(exePath)
		platform := fmt.Sprintf("%s-%s", runtime.GOOS, runtime.GOARCH)

		// Map GOARCH to our directory naming convention.
		if runtime.GOARCH == "amd64" {
			platform = runtime.GOOS + "-x64"
		}

		candidate := filepath.Join(exeDir, "third_party", "whisper", platform, whisperBinaryName())
		if _, err := os.Stat(candidate); err == nil {
			return candidate
		}
	}

	return whisperBinaryName()
}

// whisperBinaryName returns the platform-specific binary name.
func whisperBinaryName() string {
	if runtime.GOOS == "windows" {
		return "whisper-cli.exe"
	}
	return "whisper-cli"
}
